import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const base = process.env.QA_BASE_URL || 'http://localhost:3000';
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.waitForTimeout(2300);
  await page.screenshot({ path: 'outputs/qa/home-desktop-hero.png' });
  const animated = await page.locator('[data-yl-bob]').first().evaluate(el => el.getAnimations().length);
  assert.ok(animated > 0, 'Hero motion runs');
  const faq = page.getByRole('button', { name: /Do I need new tools/ });
  await faq.scrollIntoViewIfNeeded();
  await page.waitForTimeout(1400);
  await faq.click();
  assert.equal(await faq.getAttribute('aria-expanded'), 'true');
  await faq.click();
  assert.equal(await faq.getAttribute('aria-expanded'), 'false');
  await page.getByRole('heading', { name: 'How we work.' }).scrollIntoViewIfNeeded();
  await page.waitForTimeout(1400);
  await page.screenshot({ path: 'outputs/qa/home-dark-section.png' });
  await page.goto(base + '/services', { waitUntil: 'networkidle' });
  const picker = page.getByRole('button', { name: 'Spreadsheets run the business' });
  await picker.scrollIntoViewIfNeeded();
  await page.waitForTimeout(1500);
  await picker.click();
  assert.equal(await page.getByRole('link', { name: 'See how →', exact: true }).getAttribute('href'), '/services/custom-apps');
  await page.screenshot({ path: 'outputs/qa/services-picker.png' });
  await page.goto(base + '/projects', { waitUntil: 'networkidle' });
  await page.locator('[data-yl-tilt]').first().scrollIntoViewIfNeeded();
  await page.waitForTimeout(1700);
  await page.locator('[data-yl-tilt]').first().hover({ position: { x: 120, y: 80 } });
  await page.screenshot({ path: 'outputs/qa/projects-scene.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.waitForTimeout(2300);
  await page.screenshot({ path: 'outputs/qa/home-mobile-hero.png' });
  await page.getByRole('button', { name: 'Open menu', exact: true }).click();
  assert.ok(await page.locator('#mobile-menu').isVisible());
  await page.locator('#mobile-menu').getByRole('link', { name: 'Services', exact: true }).click();
  await page.waitForURL('**/services');
  await page.getByRole('button', { name: 'Book a call', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.screenshot({ path: 'outputs/qa/contact-mobile.png' });
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: animations, FAQ, picker, project hover, mobile menu and contact dialog.');
} finally { await browser.close(); }
